// gen은 testdata/emoji-data.txt(Unicode 16.0.0)에서 Extended_Pictographic 범위 표를 읽어
// emoji_table.go를 만듭니다. 네트워크를 쓰지 않습니다.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"
)

const (
	inputPath  = "testdata/emoji-data.txt"
	outputPath = "emoji_table.go"
	property   = "Extended_Pictographic"
)

type codeRange struct{ lo, hi uint32 }

func main() {
	ranges, err := readRanges()
	if err != nil {
		log.Fatal(err)
	}
	source, err := render(ranges)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(outputPath, source, 0o644); err != nil { //nolint:gosec // 소스 파일이라 0644가 맞습니다.
		log.Fatal(err)
	}
}

func readRanges() ([]codeRange, error) {
	data, err := os.ReadFile(inputPath)
	if err != nil {
		return nil, err
	}

	var ranges []codeRange
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line, _, _ := strings.Cut(scanner.Text(), "#")
		codes, prop, found := strings.Cut(line, ";")
		if !found || strings.TrimSpace(prop) != property {
			continue
		}
		lowText, highText, isRange := strings.Cut(strings.TrimSpace(codes), "..")
		if !isRange {
			highText = lowText
		}
		low, err := strconv.ParseUint(lowText, 16, 32)
		if err != nil {
			return nil, fmt.Errorf("코드 포인트 해석 실패: %q: %w", lowText, err)
		}
		high, err := strconv.ParseUint(highText, 16, 32)
		if err != nil {
			return nil, fmt.Errorf("코드 포인트 해석 실패: %q: %w", highText, err)
		}
		ranges = append(ranges, codeRange{uint32(low), uint32(high)})
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if len(ranges) == 0 {
		return nil, fmt.Errorf("%s 줄이 없습니다", property)
	}
	return ranges, nil
}

func render(ranges []codeRange) ([]byte, error) {
	var r16, r32 []codeRange
	latinOffset := 0
	for _, r := range ranges {
		if r.hi <= 0xFFFF {
			if r.hi <= 0xFF {
				latinOffset++
			}
			r16 = append(r16, r)
		} else {
			r32 = append(r32, r)
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by gen/main.go from testdata/emoji-data.txt; DO NOT EDIT.\n\n")
	out.WriteString("package honorific\n\nimport \"unicode\"\n\n")
	out.WriteString("// extendedPictographic은 Unicode 16.0.0의 Extended_Pictographic 범위입니다.\n")
	out.WriteString("var extendedPictographic = &unicode.RangeTable{\n")
	if len(r16) > 0 {
		out.WriteString("\tR16: []unicode.Range16{\n")
		for _, r := range r16 {
			fmt.Fprintf(&out, "\t\t{Lo: %#04x, Hi: %#04x, Stride: 1},\n", r.lo, r.hi)
		}
		out.WriteString("\t},\n")
	}
	if len(r32) > 0 {
		out.WriteString("\tR32: []unicode.Range32{\n")
		for _, r := range r32 {
			fmt.Fprintf(&out, "\t\t{Lo: %#06x, Hi: %#06x, Stride: 1},\n", r.lo, r.hi)
		}
		out.WriteString("\t},\n")
	}
	fmt.Fprintf(&out, "\tLatinOffset: %d,\n}\n", latinOffset)
	return format.Source(out.Bytes())
}
